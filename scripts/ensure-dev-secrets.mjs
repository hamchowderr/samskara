/**
 * Make `npm run dev` work on a fresh clone, with no secret manager.
 *
 * THE PROBLEM. The auth secrets live in Infisical, so a clone's `.env` has no
 * BETTER_AUTH_SECRET. Every branch of the provider selection in
 * src/mastra/index.ts then falls through and auth lands on the platform
 * default, which points at platform.mastra.ai — wrong for a self-hosted
 * instance, and the server reports itself healthy anyway. README and CLAUDE.md
 * both promise `npm run dev` works with a plain `.env`.
 *
 * WHAT THIS DOES. Generates the two development secrets once and appends them
 * to `.env.local`, which the Mastra CLI loads after `.env` (mastra/dist/index.js:952-956)
 * and which is gitignored. Writing them to a file rather than generating them
 * in-process means sessions and encrypted credentials survive a restart.
 *
 * WHY IT IS A `predev` SCRIPT AND NOT A BRANCH IN THE ENTRY.
 *  - npm runs `predev` only for `npm run dev`. It cannot fire for `build`,
 *    `start`, `start:secure` or `dev:secure`, so a generated secret cannot
 *    reach a real deployment by accident.
 *  - No `NODE_ENV` test is involved. The bundler folds `process.env.NODE_ENV`
 *    at build time, so a NODE_ENV-based production guard inside the entry can
 *    compile to a constant and stop guarding anything. A script that never
 *    runs in production needs no such test.
 *  - The entry stays a pure reader of config.
 *
 * It never overwrites a value that already exists in `.env` or `.env.local`,
 * so running `npm run dev` after configuring real secrets changes nothing.
 */
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync } from 'node:fs';

/** Keys this script will generate, with how to make each one and why it matters. */
const MANAGED = [
  {
    key: 'BETTER_AUTH_SECRET',
    // 32 random bytes, base64 — same shape the setup docs tell operators to
    // generate with `openssl rand -base64 32`.
    generate: () => randomBytes(32).toString('base64'),
    why: 'signs session cookies; without it auth falls through to the platform default',
  },
  {
    key: 'FACTORY_CREDENTIAL_ENCRYPTION_KEY',
    // Must decode to exactly 32 bytes — src/mastra/index.ts rejects anything else.
    generate: () => randomBytes(32).toString('base64'),
    why: 'encrypts stored provider credentials; without it they are persisted as plaintext',
  },
];

const ENV = '.env';
const ENV_LOCAL = '.env.local';

/** True when `key` has a non-empty value in any env file we load. */
function alreadySet(key) {
  for (const file of [ENV, ENV_LOCAL]) {
    if (!existsSync(file)) continue;
    const match = readFileSync(file, 'utf8').match(new RegExp(`^${key}=(.*)$`, 'm'));
    if (match && match[1].trim()) return file;
  }
  return null;
}

const missing = MANAGED.filter(entry => !alreadySet(entry.key));

if (!missing.length) {
  console.log('[dev-secrets] development secrets already present — nothing to do.');
  process.exit(0);
}

const block = [
  '',
  '# --- Generated by scripts/ensure-dev-secrets.mjs -------------------------',
  '# Local development only. This file is gitignored and is NOT the deployment',
  '# path — real deployments inject these from Infisical (see',
  '# docs/setup/secrets-infisical.md). Delete a line to have it regenerated.',
  ...missing.map(entry => `${entry.key}=${entry.generate()}`),
  '',
].join('\n');

appendFileSync(ENV_LOCAL, block);

console.log(`[dev-secrets] generated ${missing.length} development secret(s) in ${ENV_LOCAL}:`);
for (const entry of missing) console.log(`  ${entry.key} — ${entry.why}`);
console.log('[dev-secrets] local development only; deployments inject these from Infisical.');
